#!/usr/bin/env python3
"""Inject a live-health snapshot of every loop into `docs/agent-cycle.html`.

WHY THIS EXISTS

The DAG page described what each agent is *designed* to do. Asked what it was
for, the owner said: it should "help me understand about agents functionality
and how they are functioning and help me take decision on fixing them."

A static description cannot do that, and five QA rounds on its prose (11, then
7, then 13, then 13 defects) produced an accurate document that still answered
no operational question. Meanwhile `measurements/agents.json` and
`measurements/loop.json` — published by `agent-measure` several times a day —
already carried the answer. On 2026-10-31 they said four loops were failing:

    agent-discover   last 2 runs FAILED (10-26, 10-19)
    agent-prioritise last run FAILED (10-25)
    agent-research   last run FAILED (10-28)
    loop-outcomes    EVERY run it has ever had has failed

`agent-discover` finds work and `agent-prioritise` ranks it, so the backlog was
not being triaged while the open-issue count was the owner's chief complaint.
None of that was visible on a page about the agent cycle.

So this script reads those two files and inlines a compact snapshot, and the
page colours each node by it and lists what is broken at the top.

WHY INLINE RATHER THAN FETCH

The page's security property is that it is self-contained: one inline
`<script>`, no `src=`, no `fetch`, and `verify_agent_cycle_doc.py` enforces an
absolute-URL allow-list. A runtime fetch would break that, and would also fail
when the page is opened through htmlpreview or from a file:// URL. Committing
the snapshot follows the same rule `/ops` uses — committed JSON refreshed by a
workflow, never fetched at request time, so neither a GitHub nor a Google
outage can break the page.

WHY THE GATE DOES NOT REQUIRE THE SNAPSHOT TO BE CURRENT

Deliberately, and this is the load-bearing design decision. An equality check
against `measurements/*.json` would fail continuously, because the measurement
loop rewrites those files several times a day while the snapshot only moves
when someone runs this script. That is exactly the trap the first version of
`verify_agent_cycle_doc.py` fell into: it required a derived integer, two gates
landed on `main`, and it would have red-lighted the required `gates` check for
every PR in the repo. `pr-gates.yml:326-333` names the pattern.

So: the gate checks the snapshot is well-formed and that every loop in it is a
real workflow file, and **the page displays its own age**. A stale snapshot is
visible to the reader rather than fatal to the build.

    uv run python scripts/build_agent_cycle_dag.py          # rewrite the snapshot
    uv run python scripts/build_agent_cycle_dag.py --check   # is it well-formed?
"""
from __future__ import annotations

import collections
import json
from datetime import datetime  # noqa: E402  -- see _instant
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
HTML = ROOT / "docs/agent-cycle.html"
AGENTS = ROOT / "measurements/agents.json"
LOOP = ROOT / "measurements/loop.json"

BEGIN = "/* ---------- LIVE: generated by scripts/build_agent_cycle_dag.py ---------- */"
END = "/* ---------- end LIVE ---------- */"

# Node id -> the workflow whose health it shows. A node with no workflow (a
# script step, a cycle stage) simply carries no badge.
NODE_WORKFLOW = {
    "work": "agent-work.yml",
    "measure": "agent-measure.yml",
    "steward": "agent-steward.yml",
    "sweep": "agent-merge.yml",          # the cron leg of the same workflow
    "prgates": "pr-gates.yml",
    "vbuild": "verify-build.yml",
    "qagreen": "qa-on-green.yml",
    "merge": "agent-merge.yml",
    "vprod": "verify-production.yml",
    "close": "close-on-evidence.yml",
    "outcomes": "loop-outcomes.yml",
}
# `weekly` is one node standing for six workflows, so it aggregates.
WEEKLY = ("agent-discover.yml", "agent-infra.yml", "agent-research.yml",
          "agent-design.yml", "agent-sync.yml", "agent-prioritise.yml")

# `red` must mean "failing AND nothing has changed since", not "the last run
# failed". The first version of this script used `last_run_health` straight from
# agents.json, and it was WRONG about three of the four loops it called broken:
#
#   agent-prioritise  failed 10-25 on a missing WebFetch grant; #542 added it
#                     10-26. Fixed, awaiting its next weekly slot.
#   agent-discover    failed 10-26 on a transient GraphQL 500 enabling
#                     auto-merge; #563 added a 3-attempt retry 10-27, in
#                     `scripts/publish_measurements.sh` rather than in the
#                     workflow file.
#   loop-outcomes     is not failing at all -- `loop-outcomes.yml:22` documents
#                     "0 all OK/IDLE; 1 something BROKEN", so exit 1 is its
#                     CONTRACT. It has been reporting correctly for weeks.
#
# Only agent-research was genuinely broken (max-turns 80 exhausted, and its
# workflow had not changed since 10-08).
#
# So a failure is only `red` if nothing in the loop's dependency surface
# changed after it. That surface is the workflow file plus every
# `scripts/*.{sh,py}` the workflow names -- discover's fix was in a referenced
# script, so the workflow file alone would still have called it broken.
HEALTHS = {"green", "amber", "red", "fixed?", "running", "reporting", "unknown"}

# Exit 1 is this workflow's documented contract, not a failure.
#
# IMPORTED, NOT RESTATED (#628). This set lived here as a literal while
# `src/astro_ai/ops_today.py` had no equivalent at all, so the DAG page showed
# `loop-outcomes` as `reporting` and `/admin/ops` counted the same runs as loop
# failures -- one fact, two surfaces, two answers, for weeks. A second literal
# would have fixed the count and left the next divergence free to happen, so
# the declaration moved to `ops_today` (which ships in the app image; this
# script does not) and this is now a reference to it.
# `tests/test_ops_dag_agree.py` fails if the two stop being the same object.
sys.path.insert(0, str(ROOT / "src"))
from astro_ai.ops_today import CONTRACT_NONZERO  # noqa: E402


def _deps(wf: str) -> list[str]:
    """The workflow file plus every scripts/ file it names."""
    f = ROOT / ".github/workflows" / wf
    if not f.exists():
        return []
    body = f.read_text()
    # `[a-z_]+` excluded digits, so `scripts/fetch_ga4.py` -- referenced by
    # agent-discover and agent-measure -- was invisible, and a fix landing
    # there would not have moved either loop out of `red`. `.claude/` matters
    # more: an agent loop is most often fixed by editing its own prompt or
    # agent definition, and those were in no surface at all.
    return [f".github/workflows/{wf}"] + sorted(
        set(re.findall(r"scripts/[\w.-]+\.(?:sh|py)", body))
        | set(re.findall(r"\.claude/[\w/.-]+\.md", body)))


def _last_change(paths: list[str]) -> str:
    """ISO date of the most recent commit touching any of these paths."""
    if not paths:
        return ""
    import subprocess
    # %cI is LOCAL time (+05:30 here) and agents.json is UTC (...Z), so a
    # string compare opened a 5.5-hour window in which a still-broken loop
    # badges `fixed?` -- the direction that HIDES a problem. %cI is kept for
    # display; the comparison below uses instants.
    r = subprocess.run(("git", "log", "-1", "--format=%cI", "--", *paths),
                       cwd=ROOT, capture_output=True, text=True)
    return r.stdout.strip()


def _instant(iso: str):
    """Parse an ISO stamp to an aware datetime, or None."""
    if not iso:
        return None
    try:
        return datetime.fromisoformat(iso.replace("Z", "+00:00"))
    except ValueError:
        return None


def build() -> dict:
    agents = json.loads(AGENTS.read_text())
    loop = json.loads(LOOP.read_text())

    by_wf = {l["workflow"]: l for l in agents.get("loops", [])}

    # how many runs of each workflow produced something, from loop.json
    produced: collections.Counter = collections.Counter()
    ran: collections.Counter = collections.Counter()
    for row in loop.get("rows", []):
        wf = f"{row.get('workflow')}.yml"
        ran[wf] += 1
        if row.get("pr_merged") or row.get("outcome") not in (None, "", "nothing"):
            produced[wf] += 1

    def one(wf: str) -> dict | None:
        l = by_wf.get(wf)
        if l is None:
            return None
        raw = l.get("last_run_health") or "unknown"
        last = (l.get("last_run") or "")
        concl = l.get("last_conclusion") or "unknown"
        health = raw
        since = ""
        if wf in CONTRACT_NONZERO and concl in ("failure", "red"):
            # exit 1 means "found something to report", which is the point
            health = "reporting"
        elif raw in ("red", "amber") and concl != "success":
            since = _last_change(_deps(wf))
            a, b = _instant(since), _instant(last)
            if a and b and a > b:
                health = "fixed?"
        return {
            "wf": wf,
            "health": health,
            "raw": raw,
            "changed": since[:16],
            "last": last[:16],
            "concl": l.get("last_conclusion") or "unknown",
            "verdict": l.get("verdict") or "",
            "runs": l.get("runs_total") or 0,
            "ran": ran.get(wf, 0),
            "produced": produced.get(wf, 0),
        }

    live: dict[str, dict] = {}
    for node, wf in NODE_WORKFLOW.items():
        got = one(wf)
        if got:
            live[node] = got

    members = [one(w) for w in WEEKLY]
    members = [m for m in members if m]
    if members:
        worst = "green"
        # `fixed?` and `reporting` were in neither the rank list nor the
        # default, so a weekly node whose members had ALL failed badged green.
        for rank in ("red", "amber", "fixed?", "reporting", "running", "unknown"):
            if any(m["health"] == rank for m in members):
                worst = rank
                break
        live["weekly"] = {
            "wf": "six weekly loops",
            "health": worst,
            "last": max((m["last"] for m in members), default=""),
            "concl": "mixed",
            "verdict": "",
            "runs": sum(m["runs"] for m in members),
            "ran": sum(m["ran"] for m in members),
            "produced": sum(m["produced"] for m in members),
            "members": members,
        }

    return {"generated_at": agents.get("generated_at", ""), "nodes": live}


def inject(snapshot: dict) -> None:
    html = HTML.read_text()
    block = (BEGIN + "\nconst LIVE = "
             + json.dumps(snapshot, indent=0, sort_keys=True).replace("\n", "")
             + ";\n" + END)
    if BEGIN in html:
        html = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), block, html,
                      count=1, flags=re.S)
    else:
        marker = "const NODES = {}, ROW = {};"
        html = html.replace(marker, block + "\n\n" + marker, 1)
    HTML.write_text(html)


def check() -> int:
    html = HTML.read_text()
    m = re.search(re.escape(BEGIN) + r"\nconst LIVE = (.*?);\n" + re.escape(END),
                  html, re.S)
    if not m:
        print("FAIL — no LIVE snapshot in docs/agent-cycle.html; run this script")
        return 1
    try:
        snap = json.loads(m.group(1))
    except json.JSONDecodeError as exc:
        print(f"FAIL — the LIVE snapshot is not valid JSON: {exc}")
        return 1

    problems: list[str] = []
    if not snap.get("generated_at"):
        problems.append("the snapshot carries no generated_at, so the page cannot show its age")
    wfdir = ROOT / ".github/workflows"
    for node, d in (snap.get("nodes") or {}).items():
        wf = d.get("wf", "")
        if wf != "six weekly loops" and not (wfdir / wf).exists():
            problems.append(f"{node}: names {wf!r}, which is not a workflow file")
        if d.get("health") not in HEALTHS:
            problems.append(f"{node}: health {d.get('health')!r} is not one of {sorted(HEALTHS)}")
    ids = set(re.findall(r'\{\s*id:"([^"]+)"', html))
    for node in (snap.get("nodes") or {}):
        if node not in ids:
            problems.append(f"{node}: no node with that id exists on the page")

    if problems:
        print(f"FAIL — {len(problems)} problem(s) in the LIVE snapshot:")
        for p in problems:
            print(f"  - {p}")
        return 1
    n = len(snap.get("nodes") or {})
    bad = [k for k, v in (snap.get("nodes") or {}).items()
           if v.get("health") in ("red", "amber")]
    print(f"PASS — LIVE snapshot well formed: {n} nodes, generated "
          f"{snap['generated_at']}, {len(bad)} not green ({', '.join(sorted(bad)) or 'none'})")
    return 0


def main(argv: list[str]) -> int:
    if not AGENTS.exists() or not LOOP.exists():
        print("COULD NOT RUN (exit 2) — measurements/agents.json or loop.json is missing")
        return 2
    if "--check" in argv:
        return check()
    snap = build()
    inject(snap)
    bad = {k: v["health"] for k, v in snap["nodes"].items()
           if v["health"] in ("red", "amber")}
    print(f"wrote the LIVE snapshot: {len(snap['nodes'])} nodes, generated "
          f"{snap['generated_at']}")
    if bad:
        print("  not green: " + ", ".join(f"{k}={v}" for k, v in sorted(bad.items())))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
